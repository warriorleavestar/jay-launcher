namespace Amber.Core.RemoteControl.Unix;

/// <summary>
/// 控制方发来的是 PC 键盘第一套扫描码（和 Windows 的 SendInput 一样，跟键盘布局无关，见 App 的 RemoteKeyMap），
/// 这里换成 X11 的键码（Linux）和 macOS 的虚拟键码。按的是同一个物理位置的键，不按字符翻译。
/// </summary>
internal static class RemoteKeyCodes
{
    /// <summary>X11 键码：现在的 X 服务器都用 evdev 键码表，X 键码 = Linux 输入事件码 + 8；不带 E0 前缀的键，事件码就等于扫描码。</summary>
    public static uint? X11(ushort scan, bool extended)
    {
        if (!extended) return scan is >= 0x01 and <= 0x58 ? scan + 8u : null;
        int? evdev = scan switch
        {
            0x1C => 96,  // 小键盘回车
            0x1D => 97,  // 右 Ctrl
            0x35 => 98,  // 小键盘 /
            0x37 => 99,  // PrintScreen
            0x38 => 100, // 右 Alt
            0x47 => 102, // Home
            0x48 => 103, // 上
            0x49 => 104, // PageUp
            0x4B => 105, // 左
            0x4D => 106, // 右
            0x4F => 107, // End
            0x50 => 108, // 下
            0x51 => 109, // PageDown
            0x52 => 110, // Insert
            0x53 => 111, // Delete
            0x5B => 125, // 左 Win
            0x5C => 126, // 右 Win
            0x5D => 127, // 菜单键
            _ => null,
        };
        return evdev is { } e ? (uint)(e + 8) : null;
    }

    /// <summary>macOS 虚拟键码（kVK_*）。Win 键对应 Command，Alt 对应 Option；Mac 键盘上没有的键（PrintScreen、ScrollLock）返回 null。</summary>
    public static ushort? Mac(ushort scan, bool extended) => extended ? MacExtended(scan) : MacBasic(scan);

    private static ushort? MacBasic(ushort scan) => scan switch
    {
        0x01 => 0x35, // Esc
        0x02 => 0x12, 0x03 => 0x13, 0x04 => 0x14, 0x05 => 0x15, 0x06 => 0x17, 0x07 => 0x16, 0x08 => 0x1A, 0x09 => 0x1C, 0x0A => 0x19, 0x0B => 0x1D, // 1–0
        0x0C => 0x1B, 0x0D => 0x18, 0x0E => 0x33, 0x0F => 0x30, // - = 退格 Tab
        0x10 => 0x0C, 0x11 => 0x0D, 0x12 => 0x0E, 0x13 => 0x0F, 0x14 => 0x11, 0x15 => 0x10, 0x16 => 0x20, 0x17 => 0x22, 0x18 => 0x1F, 0x19 => 0x23, // Q–P
        0x1A => 0x21, 0x1B => 0x1E, 0x1C => 0x24, 0x1D => 0x3B, // [ ] 回车 左Ctrl
        0x1E => 0x00, 0x1F => 0x01, 0x20 => 0x02, 0x21 => 0x03, 0x22 => 0x05, 0x23 => 0x04, 0x24 => 0x26, 0x25 => 0x28, 0x26 => 0x25, // A–L
        0x27 => 0x29, 0x28 => 0x27, 0x29 => 0x32, 0x2A => 0x38, 0x2B => 0x2A, // ; ' ` 左Shift \
        0x2C => 0x06, 0x2D => 0x07, 0x2E => 0x08, 0x2F => 0x09, 0x30 => 0x0B, 0x31 => 0x2D, 0x32 => 0x2E, // Z–M
        0x33 => 0x2B, 0x34 => 0x2F, 0x35 => 0x2C, 0x36 => 0x3C, 0x37 => 0x43, 0x38 => 0x3A, 0x39 => 0x31, 0x3A => 0x39, // , . / 右Shift 小键盘* 左Alt 空格 CapsLock
        0x3B => 0x7A, 0x3C => 0x78, 0x3D => 0x63, 0x3E => 0x76, 0x3F => 0x60, 0x40 => 0x61, 0x41 => 0x62, 0x42 => 0x64, 0x43 => 0x65, 0x44 => 0x6D, // F1–F10
        0x45 => 0x47, // NumLock → 小键盘 Clear
        0x47 => 0x59, 0x48 => 0x5B, 0x49 => 0x5C, 0x4A => 0x4E, 0x4B => 0x56, 0x4C => 0x57, 0x4D => 0x58, 0x4E => 0x45, // 小键盘 7 8 9 - 4 5 6 +
        0x4F => 0x53, 0x50 => 0x54, 0x51 => 0x55, 0x52 => 0x52, 0x53 => 0x41, // 小键盘 1 2 3 0 .
        0x56 => 0x0A, 0x57 => 0x67, 0x58 => 0x6F, // ISO 多出来的键、F11、F12
        _ => null,
    };

    private static ushort? MacExtended(ushort scan) => scan switch
    {
        0x1C => 0x4C, 0x1D => 0x3E, 0x35 => 0x4B, 0x38 => 0x3D, // 小键盘回车 右Ctrl 小键盘/ 右Alt
        0x47 => 0x73, 0x48 => 0x7E, 0x49 => 0x74, 0x4B => 0x7B, 0x4D => 0x7C, 0x4F => 0x77, 0x50 => 0x7D, 0x51 => 0x79, // Home 上 PgUp 左 右 End 下 PgDn
        0x52 => 0x72, 0x53 => 0x75, 0x5B => 0x37, 0x5C => 0x36, 0x5D => 0x6E, // Insert(Help) Delete 左Win(Command) 右Win 菜单
        _ => null,
    };

    /// <summary>macOS 修饰键的虚拟键码对应的事件标志位（kCGEventFlagMask*），按下期间后面的键事件都要带上。</summary>
    public static ulong MacModifierFlag(ushort key) => key switch
    {
        0x38 or 0x3C => 0x20000,  // Shift
        0x3B or 0x3E => 0x40000,  // Control
        0x3A or 0x3D => 0x80000,  // Option
        0x37 or 0x36 => 0x100000, // Command
        _ => 0,
    };

    /// <summary>滚轮：Windows 一格是 120；至少算一格，最多一次 10 格（防止异常值刷屏）。</summary>
    public static int WheelNotches(int delta) => Math.Clamp((Math.Abs(delta) + 60) / 120, 1, 10);
}
